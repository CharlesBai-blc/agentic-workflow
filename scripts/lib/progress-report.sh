#!/usr/bin/env bash
# scripts/lib/progress-report.sh — templated Obsidian/Dataview reports from ledger + git log (zero tokens).
#   progress_report <layer>        -> docs/PROGRESS.md and docs/reports/LAYER-N.md (narrative block preserved)
#   incident_report <kind> <detail> -> docs/reports/INCIDENT-<ts>.md (quota pause, halt, breaker)
[[ -n "${__FLEET_PROGRESS_LOADED:-}" ]] && return 0
__FLEET_PROGRESS_LOADED=1
# shellcheck source=ledger.sh
source "$(dirname "${BASH_SOURCE[0]}")/ledger.sh"

_latest_actual_diagram() { ls -1 "$DOCS_DIR"/architecture/layer-*-actual.html 2>/dev/null | sort -V | tail -n 1 | xargs -r basename; }
_narrative_block() {  # existing narrative between markers, if any
  [[ -f "$1" ]] && awk '/<!-- narrative:start -->/{p=1;next} /<!-- narrative:end -->/{p=0} p' "$1"
}

progress_report() {  # progress_report <layer>
  local l="$1" rep="$DOCS_DIR/reports/LAYER-$1.md" narrative tag merges
  mkdir -p "$DOCS_DIR/reports" "$DOCS_DIR/architecture"
  narrative="$(_narrative_block "$rep")"
  tag="$(layer_tag "$l")"
  merges="$(git -C "$ROOT" log --merges --oneline "$tag..$(base_branch)" 2>/dev/null | head -n 60)"
  jq -r --argjson l "$l" --arg now "$(now)" --arg narrative "$narrative" --arg merges "$merges" --arg tag "$tag" \
     --arg diagram "$([[ -f "$DOCS_DIR/architecture/layer-$l-actual.html" ]] && echo "layer-$l-actual.html")" '
    def link: "[[" + . + "]]";
    (.layers[] | select(.layer==$l)) as $L
    | ([.tasks[] | select(.layer==$l)] | sort_by(.wave, .id)) as $T
    | ([.incidents[] | select(.layer==$l)]) as $I
    | (.layers[] | select(.layer==$l) | .signed_off_at) as $signed
    | "---", "title: LAYER-\($l)", "type: report", "layer: \($l)", "status: \($L.status)",
      "signed_off: \($signed // "null")", "tasks_total: \($T|length)", "tasks_merged: \($T|map(select(.status=="MERGED"))|length)",
      "incidents: \($I|length)", "strikes: \($T|map(.strikes)|add // 0)", "updated: \($now)", "tags: [report, layer-\($l)]", "---", "",
      "# Layer \($l) — \($L.title)", "",
      "Links: \("SYSTEM_SPEC"|link) · \("LAYER-\($l)-signoff"|link) · \("PROGRESS"|link) · \("STATE"|link)" +
        (if $diagram != "" then " · [Interactive architecture snapshot](../architecture/\($diagram))" else "" end) +
        " · [Target architecture](../architecture/00-target-architecture.html)", "",
      "## Narrative", "", "<!-- narrative:start -->", $narrative, "<!-- narrative:end -->", "",
      "## Tasks", "", "| task | title | status | wave | risk | strikes | rejects | PR |", "|---|---|---|---|---|---|---|---|",
      ($T[] | "| \(.id|link) | \(.title) | \(.status) | \(.wave) | \(.risk) | \(.strikes) | \(.reviews|map(select(.verdict=="REJECT"))|length) | \(if .pr_url then "[#\(.pr_number)](\(.pr_url))" else "—" end) |"),
      "", "## Incidents (strikes, retries, quarantine, surgery)", "",
      (if ($I|length)==0 then "_none_" else "| at | kind | task | detail |", "|---|---|---|---|", ($I[] | "| \(.at) | \(.kind) | \(if .task then (.task|link) else "—" end) | \(.detail) |") end),
      "", "## Merge commits since `\($tag)`", "",
      (if $merges=="" then "_none yet_" else "```text", $merges, "```" end), "",
      "## Sign-off", "", (if $L.signoff_file then "See \("LAYER-\($l)-signoff"|link) (`\($L.signoff_file)`)." else "_Phase B has not signed this layer off yet._" end), ""
  ' "$LEDGER" > "$rep.tmp" && mv -f "$rep.tmp" "$rep"
  layer_set "$l" '.report_file=$f' --arg f "docs/reports/LAYER-$l.md"
  _write_dashboard
  log "reports written: docs/PROGRESS.md, docs/reports/LAYER-$l.md"
}

_write_dashboard() {
  local out="$DOCS_DIR/PROGRESS.md" latest; latest="$(_latest_actual_diagram)"
  jq -r --arg now "$(now)" --arg latest "$latest" '
    def link: "[[" + . + "]]";
    (.tasks | to_entries | map(.value)) as $T
    | "---", "title: PROGRESS", "type: dashboard", "project: \(.project)", "run_state: \(.run_state // "IDLE")", "current_layer: \(.current_layer)",
      "tasks_total: \($T|length)", "tasks_merged: \($T|map(select(.status=="MERGED"))|length)", "updated: \($now)", "tags: [dashboard, fleet]", "---", "",
      "# \(.project) — progress dashboard", "",
      "> [!abstract] Generated by `scripts/lib/progress-report.sh` after every layer and on any pause or halt. Machine state: \("STATE"|link). Spec: \("SYSTEM_SPEC"|link).", "",
      "## Layers", "", "| layer | title | status | signed off | report | diagram |", "|---|---|---|---|---|---|",
      (.layers[] | "| \(.layer) | \(.title) | \(.status) | \(.signed_off_at // "—") | \(if .report_file then ("LAYER-\(.layer)"|link) else "—" end) | \(if .diagram_file then "[snapshot](\(.diagram_file | sub("^docs/";"")))" else "—" end) |"),
      "", "## Interactive diagrams (Archify)", "", "- [Target architecture](architecture/00-target-architecture.html)",
      (if $latest != "" then "- [Latest actual snapshot](architecture/\($latest))" else "- _no actual snapshot yet_" end), "",
      "## Task board", "", "```dataview",
      "TABLE WITHOUT ID file.link AS task, status, layer, wave, risk FROM \".agents/tasks\" WHERE type = \"task\" SORT layer ASC, wave ASC, file.name ASC",
      "```", "", "```dataview", "TABLE WITHOUT ID status, length(rows) AS count FROM \".agents/tasks\" WHERE type = \"task\" GROUP BY status", "```", "",
      "## Failures needing a human", "", "```dataview", "LIST FROM \".agents/tasks\" WHERE type = \"failure\" OR status = \"STRIKE_3_FAILED\" OR status = \"QUARANTINED\"", "```", "",
      "## Status counts (ledger)", "", "| status | count |", "|---|---|",
      ($T | group_by(.status) | map("| \(.[0].status) | \(length) |")[]),
      "", "## Quota", "", "| cli | 5h % | weekly % | state | resets at |", "|---|---|---|---|---|",
      (.quota | to_entries[] | "| \(.key) | \(.value.five_hour_pct // "?") | \(.value.weekly_pct // "?") | \(.value.state // "UNKNOWN") | \(.value.resets_at // "—") |"),
      "", "## Recent incidents", "",
      (if (.incidents|length)==0 then "_none_" else (.incidents[-10:][] | "- `\(.at)` **\(.kind)** L\(.layer) \(if .task then (.task|link) else "" end) — \(.detail)") end), ""
  ' "$LEDGER" > "$out.tmp" && mv -f "$out.tmp" "$out"
}

incident_report() {  # incident_report <kind> <detail>
  local ts out; ts="$(date -u +%Y%m%dT%H%M%SZ)"; out="$DOCS_DIR/reports/INCIDENT-$ts.md"; mkdir -p "$DOCS_DIR/reports"
  {
    printf -- '---\ntitle: INCIDENT-%s\ntype: incident\nkind: %s\nlayer: %s\nrun_state: %s\nat: %s\ntags: [incident, fleet]\n---\n\n' \
      "$ts" "$1" "$(jq '.current_layer' "$LEDGER")" "$(jq -r '.run_state' "$LEDGER")" "$(now)"
    printf '# %s\n\n%s\n\nSee [[STATE]] for the resume prompt and [[PROGRESS]] for the dashboard.\n\n## Quota at the time\n\n' "$1" "$2"
    jq -r '.quota | to_entries[] | "- \(.key): 5h=\(.value.five_hour_pct // "?")% weekly=\(.value.weekly_pct // "?")% state=\(.value.state // "UNKNOWN") resets=\(.value.resets_at // "—")"' "$LEDGER"
    printf '\n## Open tasks\n\n'
    jq -r '.tasks[] | select(.status!="MERGED") | "- [[\(.id)]] \(.status) (strikes \(.strikes))"' "$LEDGER"
  } > "$out"
  _write_dashboard
  log "incident report: $out"; echo "$out"
}
